package String_methods;

//indexOf(): method returns the index within the string of the first occurence of the specified string. 
// if the specified string is not found in the input string, the method returns -1 by default.
public class indexof_method {
	public static void main(String[] args) {
		String str="Hello Java";
		
		System.out.println(str.indexOf("Java"));
		
	}
}
